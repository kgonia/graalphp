<?php
// var_dump, var_export and print_r: raw bytes of strings and keys (not UTF-8 decoded), nesting and indentation,
// recursion, references, floats and the export syntax.
$bytes = ["a\xff\xfeb", "\xc3\xa9", "\xe2\x82", "\xed\xa0\x80", "\xf4\x90\x80\x80", "\0x\0", "", "\x80", "'\\'"];
foreach ($bytes as $s) {
    var_dump($s);
    print_r($s);
    echo "\n";
    var_export($s);
    echo "\n";
    echo print_r($s, true), '|', var_export($s, true), "\n";
}
$keyed = ["\xff" => 1, "k\xfe" => ["\x80" => "v\xc0"], 'é' => 'ü', 7 => -3, -1 => "\0", '' => null];
var_dump($keyed);
print_r($keyed);
var_export($keyed);
echo "\n";
class Point { public $x = 1; public $y = "\xff"; public $list = [1, [2, 3]]; public $next = null; }
$p = new Point;
$p->next = new Point;
var_dump($p);
print_r($p);
echo "\n";
var_export($p);
echo "\n";
$p->next->next = $p;
var_dump($p);
print_r($p);
echo "\n";
$o = new stdClass;
$o->a = 1;
$o->{'b c'} = [true, false, null];
$o->{'q\'uote'} = 'x';
var_dump($o);
var_export($o);
echo "\n";
print_r($o);
echo "\n";
var_dump((object) []);
var_export((object) []);
echo "\n";
var_export([1 => [2 => new stdClass, 3 => []], 'z' => (object) ['k' => [1]]]);
echo "\n";
print_r([[], [[]], (object) []]);
echo "\n";
$floats = [0.0, -0.0, 1.0, 0.1, 1e100, -1.5e-7, INF, -INF, NAN, 1/3, 1e15, 123456789.0];
var_dump($floats);
print_r($floats);
var_export($floats);
echo "\n";
var_dump(PHP_INT_MAX, PHP_INT_MIN, true, false, null);
var_export(PHP_INT_MIN);
echo "\n";
var_export([true, false, null, PHP_INT_MAX]);
echo "\n";
print_r([true, false, null, 1.5]);
echo "\n";
$r = [1, 2];
$r[] = &$r[0];
var_dump($r);
print_r($r);
var_export($r);
