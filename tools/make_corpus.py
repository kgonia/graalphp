"""Turns the Theme Unit Test WXR exports into corpus.php: a PHP file returning the posts' titles and contents."""
import sys, pathlib, xml.etree.ElementTree as ET

NS = {"content": "http://purl.org/rss/1.0/modules/content/", "wp": "http://wordpress.org/export/1.2/"}

def php_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
posts, seen = [], set()
for xml in sorted(src.glob("*.xml")):
    for item in ET.parse(xml).getroot().iter("item"):
        kind = item.findtext("wp:post_type", namespaces=NS)
        content = item.findtext("content:encoded", default="", namespaces=NS) or ""
        title = item.findtext("title", default="") or ""
        if kind not in ("post", "page") or not content.strip() or content in seen:
            continue
        seen.add(content)
        posts.append((title, content, "<!-- wp:" in content))
lines = ["<?php", "// Generated by tools/make_corpus.py from WordPress/theme-test-data. Do not edit.", "return ["]
for title, content, blocks in posts:
    lines.append(f"  [{php_str(title)}, {php_str(content)}, {'true' if blocks else 'false'}],")
lines.append("];")
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(posts)} posts, {sum(p[2] for p in posts)} with blocks, {sum(len(p[1]) for p in posts):,} bytes of content")
