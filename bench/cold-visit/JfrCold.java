import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import jdk.jfr.consumer.RecordedEvent;
import jdk.jfr.consumer.RecordedFrame;
import jdk.jfr.consumer.RecordedMethod;
import jdk.jfr.consumer.RecordedStackTrace;
import jdk.jfr.consumer.RecordedThread;
import jdk.jfr.consumer.RecordingFile;

/**
 * Where the requests' thread spends a cold visit, from a JFR recording with 1 ms execution samples
 * (bench/cold-visit/runs.sh diag). Each sample of a request thread ("pool-*") up to CUTOFF (epoch ms, the cold
 * visit's end; 0: all) gets
 * - a phase: the frame nearest the leaf that is the parser's (pl.codeloom.php.parser.zend: parse), the translator's
 *   (Translator, BytecodeTranslator, the DSL's builder: translate) or the guest interpreter's (the generated bytecode
 *   interpreter, the tree's nodes, OptimizedCallTarget: execution); none of these: other (the HTTP server, the
 *   context's setup);
 * - a kind, for the leaf frame: HotSpot's interpreter running it ("Interpreted"), host-compiled Java (C1 or libgraal,
 *   "JIT compiled"/"Inlined"), code Truffle compiled from PHP (the leaf's machine-code frame is
 *   OptimizedCallTarget.profiledPERoot with a guest interpreter frame inlined into it), or native code;
 * - for execution, the guest kind: the same for the frame of the nearest guest interpreter method (is the PHP code
 *   itself being interpreted by HotSpot's interpreter, by host-compiled interpreter code, or running as Truffle
 *   compiled code).
 * Also the host compilations (jdk.Compilation) up to the cutoff, and when the generated interpreter's continueAt
 * methods got compiled.
 *
 * Usage: java JfrCold.java RECORDING.jfr CUTOFF_EPOCH_MS [--top=N] [--thread=PREFIX (default pool-; the CLI's: main)]
 */
public class JfrCold {
    static final String GEN = "pl.codeloom.php.bytecode.PhpBytecodeRootNodeGen";

    static String phaseOf(RecordedFrame f) {
        String c = f.getMethod().getType().getName();
        if (c.startsWith("pl.codeloom.php.parser.zend.")) {
            return "parse";
        }
        if (c.startsWith("pl.codeloom.php.parser.Translator") || c.startsWith("pl.codeloom.php.parser.BytecodeTranslator")
                || c.startsWith(GEN + "$Builder") || c.startsWith("com.oracle.truffle.api.bytecode.BytecodeBuilder")
                || c.startsWith("com.oracle.truffle.api.bytecode.BytecodeSupport")
                || c.startsWith("com.oracle.truffle.api.bytecode.BytecodeRootNodes")) {
            return "translate";
        }
        if (guest(f)) {
            return "execution";
        }
        return null;
    }

    /** A frame of the guest interpreter: the generated bytecode interpreter, a tree node, a call target's root. */
    static boolean guest(RecordedFrame f) {
        String c = f.getMethod().getType().getName();
        String m = f.getMethod().getName();
        return (c.startsWith(GEN) && !c.startsWith(GEN + "$Builder")) || c.startsWith("pl.codeloom.php.nodes.")
                || (c.equals("com.oracle.truffle.runtime.OptimizedCallTarget")
                        && (m.equals("profiledPERoot") || m.equals("executeRootNode")));
    }

    /** The kind of the machine frame holding frames[i]. */
    static String kindAt(List<RecordedFrame> frames, int i) {
        RecordedFrame f = frames.get(i);
        String t = f.getType();
        if (t.equals("Interpreted")) {
            return "hotspot-interpreted";
        }
        if (t.equals("Native")) {
            return "native";
        }
        boolean guestInlined = false;
        int j = i;
        while (j < frames.size() && frames.get(j).getType().equals("Inlined")) {
            guestInlined |= guest(frames.get(j)) && !frames.get(j).getMethod().getType().getName()
                    .equals("com.oracle.truffle.runtime.OptimizedCallTarget");
            j++;
        }
        if (j < frames.size()) {
            RecordedMethod root = frames.get(j).getMethod();
            if (root.getName().equals("profiledPERoot") && guestInlined) {
                return "truffle-compiled";
            }
        }
        return "host-compiled";
    }

    static String group(RecordedFrame f) {
        String c = f.getMethod().getType().getName();
        if (c.startsWith(GEN)) {
            return "generated interpreter (" + (c.contains("$Builder") ? "builder" : c.contains("Uncached")
                    ? "uncached" : c.contains("Cached") ? "cached node" : "nodes") + ")";
        }
        if (c.startsWith("pl.codeloom.php.nodes.")) {
            return "pl.codeloom.php.nodes";
        }
        if (c.startsWith("pl.codeloom.php.")) {
            String[] parts = c.split("\\.");
            return parts.length > 4 ? "pl.codeloom.php." + parts[3] : "pl.codeloom.php";
        }
        if (c.startsWith("com.oracle.truffle.")) {
            return "truffle";
        }
        if (c.startsWith("java.") || c.startsWith("jdk.") || c.startsWith("sun.")) {
            return "jdk";
        }
        return "other";
    }

    static void add(Map<String, Integer> m, String k) {
        m.merge(k, 1, Integer::sum);
    }

    static void print(String title, Map<String, Integer> m, int total, int top) {
        System.out.println(title);
        m.entrySet().stream().sorted((a, b) -> b.getValue() - a.getValue()).limit(top).forEach(e -> System.out.printf(
                "  %7d  %5.1f%%  %s%n", e.getValue(), 100.0 * e.getValue() / Math.max(total, 1), e.getKey()));
    }

    public static void main(String[] args) throws Exception {
        long cutoff = Long.parseLong(args[1]);
        int top = 25;
        String threadPrefix = "pool-";
        String stacksOf = null;
        Map<String, Integer> stacks = new HashMap<>();
        for (String a : args) {
            if (a.startsWith("--top=")) {
                top = Integer.parseInt(a.substring(6));
            } else if (a.startsWith("--stacks=")) {
                stacksOf = a.substring(9);
            } else if (a.startsWith("--thread=")) {
                threadPrefix = a.substring(9);
            }
        }
        Instant jvmStart = null;
        int total = 0;
        Map<String, Integer> phaseKind = new TreeMap<>();
        Map<String, Integer> phases = new TreeMap<>();
        Map<String, Integer> guestKind = new TreeMap<>();
        Map<String, Integer> guestFrame = new TreeMap<>();
        Map<String, Integer> hsLeafGroup = new HashMap<>();
        Map<String, Integer> hsLeaf = new HashMap<>();
        Map<String, Integer> translateLeaf = new HashMap<>();
        Map<String, Integer> hostLeaf = new HashMap<>();
        Map<String, Integer> otherLeaf = new HashMap<>();
        Map<String, Integer> translateInclusive = new HashMap<>();
        Map<String, Integer> translateSelf = new HashMap<>();
        Map<String, Integer> parseInclusive = new HashMap<>();
        Map<String, Integer> threads = new TreeMap<>();
        List<RecordedEvent> compilations = new ArrayList<>();
        Map<String, Integer> deopts = new HashMap<>();
        Map<String, Integer> deoptMethods = new HashMap<>();
        int deoptTotal = 0;
        List<String> interpreterDeopts = new ArrayList<>();
        List<long[]> continueAtEvents = new ArrayList<>(); // {time ms, 1 installed / 0 lost}
        Map<String, Integer> failures = new HashMap<>();
        long firstSample = Long.MAX_VALUE;
        try (RecordingFile file = new RecordingFile(Path.of(args[0]))) {
            while (file.hasMoreEvents()) {
                RecordedEvent e = file.readEvent();
                String name = e.getEventType().getName();
                if (name.equals("jdk.JVMInformation")) {
                    jvmStart = e.getInstant("jvmStartTime");
                    continue;
                }
                if (cutoff > 0 && e.getStartTime().toEpochMilli() > cutoff) {
                    continue;
                }
                if (name.equals("jdk.Compilation")) {
                    compilations.add(e);
                    continue;
                }
                if (name.equals("jdk.CompilationFailure")) {
                    String msg = String.valueOf(e.getValue("failureMessage"));
                    add(failures, msg.length() > 160 ? msg.substring(0, 160) : msg);
                    continue;
                }
                if (name.equals("jdk.Deoptimization")) {
                    RecordedMethod m = e.getValue("method");
                    String mn = m == null ? "?" : m.getType().getName() + "." + m.getName();
                    deoptTotal++;
                    add(deoptMethods, mn);
                    if (mn.equals(GEN + "$CachedBytecodeNode.continueAt")) {
                        continueAtEvents.add(new long[] {e.getStartTime().toEpochMilli(), 0});
                    }
                    if (mn.startsWith(GEN + "$CachedBytecodeNode.continueAt") && jvmStart != null) {
                        interpreterDeopts.add(String.format("  %7.2f  %s line %s: %s/%s",
                                (e.getStartTime().toEpochMilli() - jvmStart.toEpochMilli()) / 1000.0,
                                mn.substring(GEN.length()), e.getValue("lineNumber"), e.getValue("reason"), e.getValue("action")));
                    }
                    if (mn.startsWith(GEN)) {
                        add(deopts, mn.substring(GEN.length()) + " line " + e.getValue("lineNumber") + " "
                                + e.getValue("instruction") + ": " + e.getValue("reason") + "/" + e.getValue("action"));
                    }
                    continue;
                }
                if (!name.equals("jdk.ExecutionSample")) {
                    continue;
                }
                RecordedThread thread = e.getThread("sampledThread");
                String tname = thread == null ? "?" : thread.getJavaName();
                add(threads, tname == null ? "?" : tname.replaceAll("\\d+", "N"));
                if (tname == null || !tname.startsWith(threadPrefix)) {
                    continue;
                }
                RecordedStackTrace st = e.getStackTrace();
                if (st == null) {
                    continue;
                }
                firstSample = Math.min(firstSample, e.getStartTime().toEpochMilli());
                List<RecordedFrame> frames = st.getFrames();
                total++;
                String phase = "other";
                int at = -1;
                for (int i = 0; i < frames.size(); i++) {
                    String p = phaseOf(frames.get(i));
                    if (p != null) {
                        phase = p;
                        at = i;
                        break;
                    }
                }
                String kind = kindAt(frames, 0);
                if (stacksOf != null) {
                    StringBuilder sb = new StringBuilder();
                    boolean hit = false;
                    for (int i = 0; i < Math.min(frames.size(), 40); i++) {
                        RecordedMethod m = frames.get(i).getMethod();
                        String n = m.getType().getName() + "." + m.getName();
                        hit |= n.contains(stacksOf);
                        sb.append(System.lineSeparator()).append("      ").append(n).append(':').append(frames.get(i).getLineNumber());
                    }
                    if (hit) {
                        add(stacks, sb.toString());
                    }
                }
                add(phases, phase);
                add(phaseKind, phase + " / " + kind);
                RecordedFrame leaf = frames.get(0);
                String leafName = leaf.getMethod().getType().getName() + "." + leaf.getMethod().getName();
                if (phase.equals("execution")) {
                    add(guestKind, kindAt(frames, at) + " (leaf " + kind + ")");
                    // the raw frame type of the nearest interpreter frame: for the bytecode, continueAt is
                    // Interpreted (HotSpot's interpreter), JIT compiled (host-compiled; 127 KB is never inlined by
                    // the host) or Inlined (into Truffle-compiled PHP code)
                    for (RecordedFrame f : frames) {
                        String c = f.getMethod().getType().getName();
                        if ((c.startsWith(GEN) && !c.startsWith(GEN + "$Builder")) || c.startsWith("pl.codeloom.php.nodes.")) {
                            add(guestFrame, (c.startsWith(GEN) ? "bytecode " + f.getMethod().getName() : "tree node")
                                    + " [" + f.getType() + "]");
                            break;
                        }
                    }
                }
                if (kind.equals("hotspot-interpreted")) {
                    add(hsLeafGroup, phase + " / " + group(leaf));
                    add(hsLeaf, leafName);
                } else if (kind.equals("host-compiled") && phase.equals("execution")) {
                    add(hostLeaf, leafName);
                }
                if (phase.equals("translate") || phase.equals("parse")) {
                    if (phase.equals("translate")) {
                        add(translateLeaf, leafName + " [" + leaf.getType() + "]");
                    }
                    // inclusive: each of our methods once per sample; self: the nearest of our frames, with the
                    // library method it was in
                    java.util.Set<String> seen = new java.util.HashSet<>();
                    String self = null;
                    for (RecordedFrame f : frames) {
                        String c = f.getMethod().getType().getName();
                        if (!(c.startsWith("pl.codeloom.") || c.startsWith("com.oracle.truffle.api.bytecode."))) {
                            continue;
                        }
                        String n = c.substring(c.lastIndexOf('.') + 1) + "." + f.getMethod().getName();
                        if (self == null) {
                            String l = leaf.getMethod().getType().getName();
                            self = n + (f == leaf ? "" : " > " + l.substring(l.lastIndexOf('.') + 1) + "."
                                    + leaf.getMethod().getName());
                        }
                        if (seen.add(n)) {
                            add(phase.equals("translate") ? translateInclusive : parseInclusive, n);
                        }
                    }
                    if (phase.equals("translate")) {
                        add(translateSelf, self == null ? leafName : self);
                    }
                }
                if (phase.equals("other")) {
                    add(otherLeaf, leafName + " [" + leaf.getType() + "]");
                }
            }
        }
        System.out.printf("request-thread samples (1 ms) up to the cutoff: %d; first sample %.2f s after the JVM's start%n",
                total, jvmStart == null ? -1 : (firstSample - jvmStart.toEpochMilli()) / 1000.0);
        print("phase", phases, total, top);
        print("phase / leaf kind", phaseKind, total, top);
        print("execution: the guest frame's kind (leaf kind)", guestKind, total, top);
        print("execution: the nearest interpreter frame [its type]", guestFrame, total, top);
        print("HotSpot-interpreted leaves by phase / package", hsLeafGroup, total, top);
        print("HotSpot-interpreted leaf methods", hsLeaf, total, top);
        print("host-compiled leaf methods in execution", hostLeaf, total, top);
        print("translate leaf methods", translateLeaf, total, top);
        print("translate: our methods, inclusive", translateInclusive, total, top);
        print("translate: self, at the nearest of our frames", translateSelf, total, top);
        print("parse: our methods, inclusive", parseInclusive, total, top);
        print("other leaf methods", otherLeaf, total, top);
        if (stacksOf != null) {
            print("stacks with " + stacksOf, stacks, total, 8);
        }
        print("all sampled threads (Java code only)", threads, threads.values().stream().mapToInt(i -> i).sum(), top);
        System.out.printf("deoptimizations up to the cutoff: %d%n", deoptTotal);
        print("deoptimizations by method", deoptMethods, deoptTotal, top);
        print("deoptimizations in the generated interpreter (where, reason/action)", deopts, deoptTotal, top);
        System.out.println("deoptimizations of the generated interpreter's continueAt (s after the JVM's start)");
        interpreterDeopts.forEach(System.out::println);
        print("host compilation failures", failures, failures.values().stream().mapToInt(i -> i).sum(), top);
        // how long a tier-4 continueAt was installed while the requests ran: from a successful compile's end to the
        // next deoptimization of it (an invalidation by class loading isn't a JFR deoptimization: not seen here)
        for (RecordedEvent c : compilations) {
            RecordedMethod m = c.getValue("method");
            if ((m.getType().getName() + "." + m.getName()).equals(GEN + "$CachedBytecodeNode.continueAt")
                    && c.hasField("compileLevel") && ((Number) c.getValue("compileLevel")).intValue() == 4
                    && !(c.hasField("isOsr") && c.getBoolean("isOsr")) && c.getBoolean("succeded")) {
                continueAtEvents.add(new long[] {c.getEndTime().toEpochMilli(), 1});
            }
        }
        if (!continueAtEvents.isEmpty() && firstSample != Long.MAX_VALUE) {
            continueAtEvents.sort((a, b) -> Long.compare(a[0], b[0]));
            long end = cutoff > 0 ? cutoff : continueAtEvents.get(continueAtEvents.size() - 1)[0];
            long installedSince = -1;
            long covered = 0;
            for (long[] ev : continueAtEvents) {
                long t = Math.max(ev[0], firstSample);
                if (ev[1] == 1 && installedSince < 0) {
                    installedSince = Math.min(t, end);
                } else if (ev[1] == 0 && installedSince >= 0) {
                    covered += Math.max(0, Math.min(t, end) - installedSince);
                    installedSince = -1;
                }
            }
            if (installedSince >= 0) {
                covered += Math.max(0, end - installedSince);
            }
            System.out.printf("tier-4 continueAt installed for %.2f s of the %.2f s from the first request sample to the cutoff%n",
                    covered / 1000.0, (end - firstSample) / 1000.0);
        }
        // host compilations
        double sum = 0;
        Map<String, double[]> byLevel = new TreeMap<>();
        for (RecordedEvent c : compilations) {
            double ms = c.getDuration().toNanos() / 1e6;
            sum += ms;
            String level = c.hasField("compileLevel") ? "tier " + c.getValue("compileLevel") : "?";
            byLevel.computeIfAbsent(level, k -> new double[2]);
            byLevel.get(level)[0]++;
            byLevel.get(level)[1] += ms;
        }
        System.out.printf("host compilations up to the cutoff: %d, %.0f ms on compiler threads%n", compilations.size(), sum);
        for (Map.Entry<String, double[]> e : byLevel.entrySet()) {
            System.out.printf("  %s: %.0f compilations, %.0f ms%n", e.getKey(), e.getValue()[0], e.getValue()[1]);
        }
        final Instant start = jvmStart;
        compilations.sort((a, b) -> b.getDuration().compareTo(a.getDuration()));
        System.out.println("longest host compilations (start s after the JVM's, ms, tier, code bytes, method)");
        for (RecordedEvent c : compilations.subList(0, Math.min(top, compilations.size()))) {
            describe(c, start);
        }
        System.out.println("the generated interpreter's continueAt / the tree's root execute compilations");
        compilations.sort((a, b) -> a.getStartTime().compareTo(b.getStartTime()));
        for (RecordedEvent c : compilations) {
            RecordedMethod m = c.getValue("method");
            String n = m.getType().getName() + "." + m.getName();
            if ((n.startsWith(GEN) && m.getName().equals("continueAt")) || n.endsWith("OptimizedCallTarget.profiledPERoot")
                    || n.endsWith("OptimizedCallTarget.executeRootNode")) {
                describe(c, start);
            }
        }
    }

    static void describe(RecordedEvent c, Instant start) {
        RecordedMethod m = c.getValue("method");
        System.out.printf("  %7.2f %8.1f  %s  %7s  %s%s%s%n",
                start == null ? -1 : (c.getStartTime().toEpochMilli() - start.toEpochMilli()) / 1000.0,
                c.getDuration().toNanos() / 1e6, c.hasField("compileLevel") ? c.getValue("compileLevel") : "?",
                c.hasField("codeSize") ? c.getValue("codeSize") : "?", m.getType().getName() + "." + m.getName(),
                c.hasField("isOsr") && c.getBoolean("isOsr") ? " (OSR)" : "",
                c.hasField("succeded") && !c.getBoolean("succeded") ? " FAILED" : "");
    }
}
